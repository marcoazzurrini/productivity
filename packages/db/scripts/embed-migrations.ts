import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/**
 * Copies the SQL that drizzle-kit wrote into src/migrations.ts. The desktop
 * app is one bundled file with no migrations folder next to it, so the SQL
 * has to live in code.
 *
 * Usage: bun run db:generate (runs drizzle-kit first, then this)
 */

const root = path.resolve(import.meta.dir, "..");
const folder = path.join(root, "migrations");
const target = path.join(root, "src", "migrations.ts");

const migrations = readdirSync(folder, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .toSorted()
  .map((name) => ({
    name,
    sql: readFileSync(path.join(folder, name, "migration.sql"), "utf-8"),
  }));

const source = `// Generated by \`bun run db:generate\` from migrations/. Do not edit.

export interface Migration {
  name: string;
  sql: string;
}

export const migrations: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(target, source);

process.stdout.write(`Embedded ${migrations.length} migrations in ${target}\n`);
